"""News build artifacts that must never survive a newly generated script."""
from __future__ import annotations

import shutil
from pathlib import Path


_DIRS = ("voice", "bubbles", "_prescale")
_FILES = ("remotion.mp4", "output.mp4", "timing.json")


def discard_news_intermediates(work_dir: Path) -> list[Path]:
    """Remove derived news artifacts, leaving source JSON and QA records intact.

    This is deliberately scoped to files regenerated by ``build_news``.  It is
    safe to call after a generator has written a new ``script.json``.
    """
    removed: list[Path] = []
    for name in _DIRS:
        path = work_dir / name
        if path.exists():
            shutil.rmtree(path)
            removed.append(path)
    for name in _FILES:
        path = work_dir / name
        if path.exists():
            path.unlink()
            removed.append(path)
    return removed
